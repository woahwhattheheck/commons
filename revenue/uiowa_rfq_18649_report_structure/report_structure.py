#!/usr/bin/env python3
"""Report production structure for University of Iowa RFQ 18649 (UIOWA-082).

STATUS: PROPOSED REPORT STRUCTURE / NOT A UNIVERSITY FINDING.

What this is
------------
`content_map.json` maps every required RFQ report element to a report section and
to the inputs that section needs. This module makes that map *executable*: it
loads the map, checks its coverage, verifies the declared inputs against the
field names the other RFQ lanes actually landed, and renders both the editable
template and a populated synthetic sample from the same structure.

Why the checker fails closed on "a section with no source"
----------------------------------------------------------
A final report fails in two directions. An RFQ element with no section is the
obvious one and is easy to catch. The quieter one is a prose section that cites
nothing: that is exactly where an unsupported assertion enters a report and then
gets quoted back as a finding. So a section declaring no required input is an
error, not a style note.

Why the field names are not invented
------------------------------------
`input_schemas.json` was generated by reading the headers of the registers other
seats actually checked in - the EV/OBS/FND evidence chain, the peer
comparability table, the policy context register, the framework crosswalk, the
SDLC worksheet. `--verify-workbench` re-reads those files and fails if a pinned
field name has drifted. A template that renames its neighbours' fields is a
template nobody can feed.

Python 3 standard library only. No network.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from dataclasses import dataclass, field
from typing import Any, Sequence

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_MAP = os.path.join(HERE, "content_map.json")
DEFAULT_SCHEMAS = os.path.join(HERE, "input_schemas.json")
DEFAULT_FIXTURES = os.path.join(HERE, "fixtures")

# Severity for a coverage issue. ERROR fails the check; WARN is reported and
# does not fail, so the checker stays usable on a report still being drafted.
ERROR = "ERROR"
WARN = "WARN"

UNKNOWN_TOKEN = "UNKNOWN"


@dataclass
class Issue:
    code: str
    severity: str
    subject: str
    detail: str

    def __str__(self) -> str:
        return f"[{self.severity}] {self.code}  {self.subject}: {self.detail}"


@dataclass
class ContentMap:
    raw: dict
    elements: list[dict] = field(default_factory=list)
    sections: list[dict] = field(default_factory=list)
    excluded: list[dict] = field(default_factory=list)

    @property
    def element_ids(self) -> list[str]:
        return [e["element_id"] for e in self.elements]

    @property
    def section_ids(self) -> list[str]:
        return [s["section_id"] for s in self.sections]

    def element(self, eid: str) -> dict | None:
        return next((e for e in self.elements if e["element_id"] == eid), None)

    def sections_for(self, eid: str) -> list[dict]:
        return [s for s in self.sections if eid in s.get("covers", [])]


def load_map(path: str = DEFAULT_MAP) -> ContentMap:
    with open(path, encoding="utf-8") as f:
        raw = json.load(f)
    return ContentMap(raw=raw,
                      elements=raw.get("rfq_elements", []),
                      sections=raw.get("sections", []),
                      excluded=raw.get("excluded_deliverables", []))


def load_schemas(path: str = DEFAULT_SCHEMAS) -> dict[str, dict]:
    with open(path, encoding="utf-8") as f:
        return json.load(f).get("datasets", {})


# ---------------------------------------------------------------------------
# Coverage checker
# ---------------------------------------------------------------------------

def check_coverage(cmap: ContentMap, schemas: dict[str, dict]) -> list[Issue]:
    """Every required element has a section; every section has a source.

    Returns issues in a stable order so a CI diff of the output is readable.
    """
    issues: list[Issue] = []

    # -- structural integrity of the map itself ----------------------------
    seen_sections: set[str] = set()
    for s in cmap.sections:
        sid = s.get("section_id", "<missing>")
        if sid in seen_sections:
            issues.append(Issue("DUPLICATE_SECTION_ID", ERROR, sid,
                                "two sections share this identifier; citations would be ambiguous"))
        seen_sections.add(sid)

    seen_elements: set[str] = set()
    for e in cmap.elements:
        eid = e.get("element_id", "<missing>")
        if eid in seen_elements:
            issues.append(Issue("DUPLICATE_ELEMENT_ID", ERROR, eid,
                                "two RFQ elements share this identifier"))
        seen_elements.add(eid)

    # -- 1. an RFQ element with no section ---------------------------------
    for e in cmap.elements:
        eid = e["element_id"]
        if not cmap.sections_for(eid):
            issues.append(Issue("UNMAPPED_ELEMENT", ERROR, eid,
                                f"required RFQ element '{e.get('name', eid)}' is not covered "
                                f"by any section; the report would ship without it"))

    # -- 2. a section with no source, and section->element integrity -------
    for s in cmap.sections:
        sid = s.get("section_id", "<missing>")
        covers = s.get("covers", [])
        if not covers:
            issues.append(Issue("ORPHAN_SECTION", ERROR, sid,
                                "section covers no RFQ element; it is either unnecessary "
                                "or an element is missing from the map"))
        for eid in covers:
            if cmap.element(eid) is None:
                issues.append(Issue("DANGLING_ELEMENT_REF", ERROR, sid,
                                    f"covers unknown element '{eid}'"))

        inputs = s.get("required_inputs", [])
        if not inputs:
            issues.append(Issue("SECTION_WITHOUT_SOURCE", ERROR, sid,
                                "section declares no required input; prose here would rest "
                                "on nothing a reader can check"))

        # -- 3/4. dataset and field bindings -------------------------------
        for i, binding in enumerate(inputs):
            ds = binding.get("dataset")
            where = f"{sid}.required_inputs[{i}]"
            if ds not in schemas:
                issues.append(Issue("UNKNOWN_DATASET", ERROR, where,
                                    f"dataset '{ds}' is not declared in input_schemas.json"))
                continue
            known = set(schemas[ds].get("fields", []))
            declared = binding.get("fields", [])
            if not declared:
                issues.append(Issue("INPUT_WITHOUT_FIELDS", ERROR, where,
                                    f"dataset '{ds}' is bound but no field is named; "
                                    f"the section cannot state what it consumes"))
            for fname in declared:
                if fname not in known:
                    issues.append(Issue("FIELD_NOT_IN_SCHEMA", ERROR, where,
                                        f"'{fname}' is not a field of '{ds}'. Use the real "
                                        f"register field name or add the field to the schema; "
                                        f"do not invent one."))
            if not binding.get("why"):
                issues.append(Issue("INPUT_WITHOUT_RATIONALE", WARN, where,
                                    f"dataset '{ds}' is bound with no stated reason"))

        # -- report hygiene the RFQ actually depends on --------------------
        if not s.get("traceability_rule"):
            issues.append(Issue("MISSING_TRACEABILITY_RULE", ERROR, sid,
                                "no traceability rule; statements here could not be followed "
                                "back to a finding or source"))
        if not s.get("unknown_rule"):
            issues.append(Issue("MISSING_UNKNOWN_RULE", ERROR, sid,
                                "no rule for missing evidence; this is where an absent input "
                                "turns into a zero or a pass"))
        if not s.get("prompts"):
            issues.append(Issue("SECTION_WITHOUT_PROMPTS", WARN, sid,
                                "no author prompts; the template would give the writer nothing"))

    # -- the three exclusions must remain declared -------------------------
    declared_guards = {x.get("guard_class") for x in cmap.excluded}
    for required in ("audit_verdict", "individual_evaluation", "product_procurement"):
        if required not in declared_guards:
            issues.append(Issue("MISSING_EXCLUSION", ERROR, required,
                                "the work order requires this deliverable stay out of scope; "
                                "it is not declared in excluded_deliverables"))

    return issues


def errors(issues: Sequence[Issue]) -> list[Issue]:
    return [i for i in issues if i.severity == ERROR]


# ---------------------------------------------------------------------------
# Workbench verification: are the pinned field names still the real ones?
# ---------------------------------------------------------------------------

def verify_workbench(schemas: dict[str, dict], repo_root: str) -> list[Issue]:
    """Re-read the checked-in registers and compare against the pinned schema.

    Datasets marked `lane_local` have no upstream file yet and are skipped - they
    are this lane's own fixtures, declared with reused field names so a real
    register can replace them without a rename pass.
    """
    issues: list[Issue] = []
    for name, spec in sorted(schemas.items()):
        if spec.get("provenance") != "workbench_pinned":
            continue
        rel = spec.get("source_path", "")
        path = os.path.join(repo_root, rel)
        if not os.path.exists(path):
            issues.append(Issue("WORKBENCH_FILE_MISSING", WARN, name,
                                f"{rel} not found under {repo_root}; cannot verify pinned fields"))
            continue
        try:
            with open(path, newline="", encoding="utf-8") as f:
                header = next(csv.reader(f))
        except StopIteration:
            issues.append(Issue("WORKBENCH_FILE_EMPTY", ERROR, name, f"{rel} has no header row"))
            continue
        real = set(header)
        pinned = list(spec.get("fields", []))
        drifted = [p for p in pinned if p not in real]
        if drifted:
            issues.append(Issue("SCHEMA_DRIFT", ERROR, name,
                                f"pinned field(s) {drifted} are no longer in {rel}; "
                                f"the upstream register changed shape"))
        added = [r for r in header if r not in set(pinned)]
        if added:
            issues.append(Issue("SCHEMA_NEW_FIELDS", WARN, name,
                                f"{rel} now carries field(s) {added} the map does not consume yet"))
    return issues


# ---------------------------------------------------------------------------
# Fixture loading (synthetic, labeled fiction)
# ---------------------------------------------------------------------------

def load_fixture(schemas: dict[str, dict], dataset: str,
                 fixtures_dir: str = DEFAULT_FIXTURES) -> list[dict]:
    """Load a dataset's synthetic rows, if this lane carries a fixture for it."""
    candidates = [
        os.path.join(fixtures_dir, f"synthetic_{dataset}.csv"),
        os.path.join(fixtures_dir, os.path.basename(schemas.get(dataset, {}).get("source_path", ""))),
    ]
    for c in candidates:
        if c and os.path.exists(c):
            with open(c, newline="", encoding="utf-8") as f:
                return list(csv.DictReader(f))
    return []


def load_all_fixtures(schemas: dict[str, dict],
                      fixtures_dir: str = DEFAULT_FIXTURES) -> dict[str, list[dict]]:
    return {ds: load_fixture(schemas, ds, fixtures_dir) for ds in schemas}


