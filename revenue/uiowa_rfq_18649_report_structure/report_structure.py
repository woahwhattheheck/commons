_FICTION_BANNER = (
    "> **SYNTHETIC EXAMPLE - NOT A UNIVERSITY FINDING.** Every group, finding, "
    "identifier, date and number below is fiction, written to exercise the report "
    "structure. Nothing here describes the University of Iowa.\n"
)

_TEMPLATE_BANNER = (
    "> **EDITABLE TEMPLATE.** Replace every `<...>` placeholder. Do not delete a "
    "section to hide a gap: a section with nothing to report says so and cites the "
    "open question instead. Missing evidence stays `UNKNOWN` - it never becomes a "
    "zero, a pass, or a maturity score.\n"
)


def _md_table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    def esc(v: Any) -> str:
        s = "" if v is None else str(v)
        return s.replace("|", "\\|").replace("\n", " ")
    out = ["| " + " | ".join(esc(h) for h in headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(esc(c) for c in r) + " |")
    return "\n".join(out)


def _blank(v: str) -> str:
    """An empty cell is reported as UNKNOWN, never as an implied zero or pass."""
    v = (v or "").strip()
    return v if v else UNKNOWN_TOKEN


def render_template(cmap: ContentMap, schemas: dict[str, dict]) -> str:
    """The editable report template: structure, prompts, and input contracts."""
    L: list[str] = []
    L.append("# University of Iowa RFQ 18649 - Assessment Report")
    L.append("")
    L.append("**Status:** `<DRAFT | FINAL>`  ")
    L.append("**Prepared by:** `<assessment team>`  ")
    L.append("**Reporting period:** `<start>` to `<end>`  ")
    L.append("**Report structure:** `" + cmap.raw.get("map_id", "") + "`")
    L.append("")
    L.append(_TEMPLATE_BANNER)
    L.append("## Scope boundary")
    L.append("")
    L.append("This assessment describes current practice against reference frameworks used as "
             "interview and artifact prompts. It is not a formal audit and issues no compliance "
             "determination, certification or attestation. It assesses organizational practice; "
             "no statement rates, ranks or evaluates a named individual. It describes capabilities "
             "the University may need; no vendor selection or product purchase is recommended.")
    L.append("")
    for x in cmap.excluded:
        L.append(f"- **Out of scope - {x['name']}.** {x['why']}")
    L.append("")
    L.append("---")
    L.append("")
    for s in cmap.sections:
        L.append(f"## {s['number']}. {s['title']}")
        L.append("")
        L.append(f"*Audience: {s.get('audience', 'all')}. Covers: "
                 f"{', '.join(s.get('covers', []))}.*")
        L.append("")
        L.append(f"**Purpose.** {s.get('purpose', '')}")
        L.append("")
        L.append("**Inputs this section requires**")
        L.append("")
        L.append(_md_table(
            ["dataset", "fields consumed", "why"],
            [[b["dataset"], ", ".join(f"`{x}`" for x in b.get("fields", [])), b.get("why", "")]
             for b in s.get("required_inputs", [])]))
        L.append("")
        L.append(f"**Traceability rule.** {s.get('traceability_rule', '')}")
        L.append("")
        L.append(f"**Missing-evidence rule.** {s.get('unknown_rule', '')}")
        L.append("")
        L.append("**Write this section by answering:**")
        L.append("")
        for p in s.get("prompts", []):
            L.append(f"- {p}")
        L.append("")
        L.append("> `<section content here>`")
        L.append("")
        L.append("---")
        L.append("")
    return "\n".join(L)


def _matrix_block(rows: list[dict]) -> str:
    """The 12-cell view. An unassessed cell stays visibly unassessed."""
    groups = ["ESS", "RIS", "IAM"]
    areas = ["SD", "SEC", "DEP", "AI"]
    idx = {(r.get("group"), r.get("area")): r for r in rows}
    out = [_md_table(
        ["group \\ area", "SD software dev", "SEC security", "DEP deployment/ops", "AI readiness"],
        [[g] + [(lambda r: f"{_blank(r.get('status'))} ({_blank(r.get('confidence'))}) "
                           f"{r.get('finding_id', '')}".strip()
                 if r else f"{UNKNOWN_TOKEN} - not assessed")(idx.get((g, a)))
                for a in areas]
         for g in groups])]
    assessed = [r for r in rows if r.get("status") not in ("", UNKNOWN_TOKEN, None)]
    out.append("")
    out.append(f"*{len(assessed)} of 12 cells carry an assessed status. "
               f"Cells shown as `{UNKNOWN_TOKEN} - not assessed` are a statement about the "
               f"evidence collected, not about the group, and are excluded from every count "
               f"of assessed cells rather than counted as zero.*")
    return "\n".join(out)


def render_sample(cmap: ContentMap, schemas: dict[str, dict],
                  data: dict[str, list[dict]]) -> str:
    """A populated synthetic report rendered through the same structure."""
    matrix = data.get("finding_matrix", [])
    evidence = data.get("evidence_register", [])
    recs = data.get("recommendation_register", [])
    themes = data.get("theme_register", [])
    peers = data.get("peer_context_table", [])

    L: list[str] = []
    L.append("# University of Iowa RFQ 18649 - Assessment Report (SYNTHETIC SAMPLE)")
    L.append("")
    L.append(_FICTION_BANNER)
    L.append("**Status:** SYNTHETIC SAMPLE  ")
    L.append("**Report structure:** `" + cmap.raw.get("map_id", "") + "`  ")
    L.append("**Purpose:** demonstrate that the structure accepts the planned matrix and "
             "register outputs and renders a complete report from them.")
    L.append("")
    L.append("## Scope boundary")
    L.append("")
    L.append("This assessment is not a formal audit and issues no compliance determination, "
             "certification or attestation. No statement rates, ranks or evaluates a named "
             "individual. No vendor selection or product purchase is recommended.")
    L.append("")
    L.append("---")
    L.append("")

    for s in cmap.sections:
        sid = s["section_id"]
        L.append(f"## {s['number']}. {s['title']}")
        L.append("")

        if sid == "SEC-01":
            supported = [r for r in matrix if r.get("status") == "SUPPORTED"]
            gaps = [r for r in matrix if r.get("status") in ("PARTIAL", "CONFLICT")]
            unassessed = [r for r in matrix if r.get("status") == UNKNOWN_TOKEN]
            L.append(f"Twelve group-by-area cells were in scope. {len(matrix)} were reached; "
                     f"{len(supported)} are supported by direct current evidence, "
                     f"{len(gaps)} are partial or carry conflicting evidence, and "
                     f"{len(unassessed)} could not be assessed with the evidence supplied.")
            L.append("")
            for r in supported[:2]:
                L.append(f"- **Holds up.** {r.get('statement')} ({r['finding_id']}, "
                         f"confidence {r.get('confidence')}).")
            for r in gaps[:2]:
                L.append(f"- **Does not yet hold up.** {r.get('statement')} ({r['finding_id']}, "
                         f"confidence {r.get('confidence')}). {r.get('scope_limit')}")
            for r in unassessed:
                L.append(f"- **Not assessed.** {r.get('group')}/{r.get('area')} "
                         f"({r['finding_id']}): {r.get('scope_limit')} "
                         f"Resolving question: {r.get('follow_up_question')}")
            L.append("")
            near = [r for r in recs if r.get("horizon") == "0-90"]
            if near:
                L.append("Proposed in the first 90 days:")
                L.append("")
                for r in near:
                    L.append(f"- {r['recommendation_id']}: {r.get('statement')} "
                             f"(from {r.get('finding_refs')})")
            L.append("")

        elif sid == "SEC-02":
            L.append("In scope: ESS, RIS and IAM across software development (SD), security (SEC), "
                     "deployment and operations (DEP), and AI readiness (AI) - twelve cells.")
            L.append("")
            L.append(_md_table(["group", "areas reached", "areas not assessed"],
                               [[g,
                                 ", ".join(sorted(r["area"] for r in matrix
                                                  if r.get("group") == g
                                                  and r.get("status") != UNKNOWN_TOKEN)) or "none",
                                 ", ".join(sorted(r["area"] for r in matrix
                                                  if r.get("group") == g
                                                  and r.get("status") == UNKNOWN_TOKEN)) or "none"]
                                for g in ("ESS", "RIS", "IAM")]))
            L.append("")

        elif sid == "SEC-03":
            kinds: dict[str, int] = {}
            for e in evidence:
                kinds[e.get("source_type", UNKNOWN_TOKEN)] = kinds.get(e.get("source_type", UNKNOWN_TOKEN), 0) + 1
            L.append(f"{len(evidence)} synthetic evidence items were collected across "
                     f"{len(kinds)} source types.")
            L.append("")
            L.append(_md_table(["source type", "items"],
                               [[k, str(v)] for k, v in sorted(kinds.items())]))
            L.append("")
            L.append("Framework references were used as interview and artifact prompts. A framework "
                     "practice is a prompt, not a criterion, and no cell is scored against one.")
            L.append("")

        elif sid == "SEC-04":
            L.append("Confidence is recorded on five dimensions and is never averaged into a single "
                     "number. The dimensions are reported alongside each evidence item in Appendix A.")
            L.append("")
            dist: dict[str, int] = {}
            for e in evidence:
                dist[e.get("confidence", UNKNOWN_TOKEN)] = dist.get(e.get("confidence", UNKNOWN_TOKEN), 0) + 1
            L.append(_md_table(["confidence", "evidence items", "meaning"],
                               [[k, str(v),
                                 {"HIGH": "direct, current, representative, corroborated",
                                  "MODERATE": "direct but narrow, or current without independent corroboration",
                                  "LOW": "indirect, stale, single-source, or uncorroborated",
                                  "NOT_EVIDENCED": "no source was observed for the claim",
                                  "UNRESOLVED": "material sources disagree and the conflict is open",
                                  }.get(k, "")]
                                for k, v in sorted(dist.items())]))
            L.append("")
            L.append("`NOT_EVIDENCED` means no source was reviewed. It is not a negative finding "
                     "about the group, and it is not a zero.")
            L.append("")

        elif sid == "SEC-05":
            if peers:
                L.append(_md_table(
                    ["peer", "measure", "value", "denominator/scope", "comparison status", "note"],
                    [[p.get("peer"), p.get("metric_or_measure"), p.get("value"),
                      p.get("denominator_or_scope"), p.get("comparison_status"),
                      p.get("comparability_notes")] for p in peers]))
                L.append("")
            L.append("Every row above carries its own comparison status. Rows marked `context_only` "
                     "or `not_comparable_without_normalization` cannot support a comparison and are "
                     "presented as context. No percentile, ranking or standing against peers is "
                     "stated anywhere in this report.")
            L.append("")

        elif sid == "SEC-06":
            L.append(_matrix_block(matrix))
            L.append("")

        elif sid in ("SEC-07", "SEC-08", "SEC-09"):
            grp = {"SEC-07": "ESS", "SEC-08": "RIS", "SEC-09": "IAM"}[sid]
            rows = [r for r in matrix if r.get("group") == grp]
            for r in rows:
                L.append(f"### {r['finding_id']} - {grp} / {r.get('area')} "
                         f"({_blank(r.get('status'))}, confidence {_blank(r.get('confidence'))})")
                L.append("")
                L.append(r.get("statement", ""))
                L.append("")
                L.append(f"*Scope limit:* {r.get('scope_limit')}")
                L.append("")
                supp = [e for e in evidence if e.get("finding_id") == r["finding_id"]]
                if supp:
                    L.append(_md_table(
                        ["evidence", "type", "claim", "directness", "recency",
                         "representativeness", "corroboration", "confidence"],
                        [[e.get("evidence_id"), e.get("source_type"), e.get("claim"),
                          e.get("directness"), e.get("recency"), e.get("representativeness"),
                          e.get("corroboration"), e.get("confidence")] for e in supp]))
                else:
                    L.append(f"*No evidence item is registered for this finding - "
                             f"status {UNKNOWN_TOKEN}.*")
                L.append("")
                if r.get("follow_up_question"):
                    L.append(f"*Open question:* {r['follow_up_question']}")
                    L.append("")

        elif sid == "SEC-10":
            for t in themes:
                L.append(f"### {t['theme_id']} - {t.get('statement')}")
                L.append("")
                L.append(f"*Spans:* {t.get('groups_spanned')} / {t.get('areas_spanned')}  ")
                L.append(f"*Findings:* {t.get('finding_refs')}  ")
                L.append(f"*Counter-evidence:* {_blank(t.get('counter_evidence'))}  ")
                L.append(f"*Scope limit:* {t.get('scope_limit')}")
                L.append("")
            L.append("Each theme names the individual findings it spans. A theme is a reading of "
                     "those findings, not a replacement for them; the findings remain the record.")
            L.append("")

        elif sid == "SEC-11":
            for g in ("ESS", "RIS", "IAM", "CROSS"):
                rows = [r for r in recs if r.get("group") == g]
                if not rows:
                    continue
                L.append(f"### {g}")
                L.append("")
                L.append(_md_table(
                    ["id", "recommendation", "from findings", "rationale", "resource note", "depends on"],
                    [[r["recommendation_id"], r.get("statement"), r.get("finding_refs"),
                      r.get("rationale"), _blank(r.get("resource_note")),
                      _blank(r.get("dependency"))] for r in rows]))
                L.append("")
            L.append("Each recommendation names the findings that motivate it and does not inherit "
                     "their confidence. Recommendations describe capabilities and decisions; "
                     "selecting or purchasing a product is the University's own process.")
            L.append("")

        elif sid == "SEC-12":
            for h, label in (("0-90", "0-90 days"), ("90-180", "90-180 days"),
                             ("180+", "180+ days"), (UNKNOWN_TOKEN, "Unsequenced - estimate missing")):
                rows = [r for r in recs if (r.get("horizon") or UNKNOWN_TOKEN) == h]
                L.append(f"### {label}")
                L.append("")
                if rows:
                    L.append(_md_table(["id", "recommendation", "depends on", "resource note"],
                                       [[r["recommendation_id"], r.get("statement"),
                                         _blank(r.get("dependency")), _blank(r.get("resource_note"))]
                                        for r in rows]))
                else:
                    L.append("*No items.*")
                L.append("")
            L.append(f"An item whose horizon is `{UNKNOWN_TOKEN}` sits in the unsequenced bucket with "
                     f"the missing input named. It is not defaulted into a later phase, which would "
                     f"present a guess as a plan.")
            L.append("")

        elif sid == "SEC-13":
            L.append(_md_table(
                ["evidence", "finding", "group/area", "type", "source", "captured", "represents",
                 "claim", "scope limit", "state", "confidence"],
                [[e.get("evidence_id"), e.get("finding_id"),
                  f"{e.get('group')}/{e.get('area')}", e.get("source_type"), e.get("source_ref"),
                  e.get("captured_at"), e.get("represented_period"), e.get("claim"),
                  e.get("scope_limit"), e.get("evidence_state"), e.get("confidence")]
                 for e in evidence]))
            L.append("")
            cited = {r["finding_id"] for r in matrix}
            backed = {e.get("finding_id") for e in evidence}
            missing = sorted(cited - backed)
            if missing:
                L.append(f"*Findings with no registered evidence item: {', '.join(missing)}. "
                         f"These are carried as {UNKNOWN_TOKEN} in the matrix and are listed in "
                         f"Appendix C.*")
                L.append("")

        elif sid == "SEC-14":
            L.append("*In a real engagement this appendix is rendered from the landed source and "
                     "version registers (`source_version_register`, `policy_context_register`), "
                     "pinning every framework to the version actually used. This synthetic sample "
                     "does not restate those registers.*")
            L.append("")

        elif sid == "SEC-15":
            open_rows = [r for r in matrix
                         if r.get("status") in (UNKNOWN_TOKEN, "PARTIAL", "CONFLICT")]
            L.append(_md_table(["finding", "group/area", "status", "what is unresolved",
                                "what would resolve it"],
                               [[r["finding_id"], f"{r.get('group')}/{r.get('area')}",
                                 r.get("status"), r.get("scope_limit"),
                                 _blank(r.get("follow_up_question"))] for r in open_rows]))
            L.append("")
            L.append("This appendix exists so that an absent input never has to become a zero, a "
                     "pass or a rating anywhere else in the report.")
            L.append("")

        else:
            L.append("*(no sample renderer for this section)*")
            L.append("")

        L.append("---")
        L.append("")

    return "\n".join(L)


def content_map_rows(cmap: ContentMap) -> list[list[str]]:
    """Flat element -> section -> input view, for the operator-facing CSV."""
    rows: list[list[str]] = []
    for e in cmap.elements:
        secs = cmap.sections_for(e["element_id"])
        if not secs:
            rows.append([e["element_id"], e["name"], "", "", "", "", e.get("must_not", "")])
            continue
        for s in secs:
            for b in s.get("required_inputs", []):
                rows.append([e["element_id"], e["name"], s["section_id"],
                             f"{s['number']}. {s['title']}", b.get("dataset", ""),
                             "; ".join(b.get("fields", [])), e.get("must_not", "")])
    return rows


CONTENT_MAP_HEADERS = ["element_id", "rfq_element", "section_id", "section",
                       "required_dataset", "required_fields", "element_must_not"]


