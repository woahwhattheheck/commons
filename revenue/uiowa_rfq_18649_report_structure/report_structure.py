def _report_issues(issues: Sequence[Issue], title: str) -> None:
    errs = errors(issues)
    warns = [i for i in issues if i.severity == WARN]
    print(title)
    print("=" * len(title))
    print(f"errors: {len(errs)}   warnings: {len(warns)}")
    for i in issues:
        print("  " + str(i))
    if not issues:
        print("  (none)")
    print()


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="UIOWA-082 report structure: check and render.")
    ap.add_argument("--map", default=DEFAULT_MAP)
    ap.add_argument("--schemas", default=DEFAULT_SCHEMAS)
    ap.add_argument("--fixtures", default=DEFAULT_FIXTURES)
    ap.add_argument("--check", action="store_true", help="run the coverage checker")
    ap.add_argument("--verify-workbench", metavar="REPO_ROOT", default=None,
                    help="re-read the landed registers and fail on pinned-field drift")
    ap.add_argument("--render-template", metavar="PATH", default=None)
    ap.add_argument("--render-sample", metavar="PATH", default=None)
    ap.add_argument("--render-map-csv", metavar="PATH", default=None)
    ap.add_argument("--scope-guard", action="store_true",
                    help="run the scope guard over the rendered template and sample")
    a = ap.parse_args(argv)

    cmap = load_map(a.map)
    schemas = load_schemas(a.schemas)
    rc = 0

    if a.check or not any([a.render_template, a.render_sample, a.render_map_csv,
                           a.verify_workbench, a.scope_guard]):
        issues = check_coverage(cmap, schemas)
        _report_issues(issues, "COVERAGE CHECK")
        print(f"{len(cmap.elements)} RFQ elements -> {len(cmap.section_ids)} sections")
        for e in cmap.elements:
            secs = ", ".join(s["section_id"] for s in cmap.sections_for(e["element_id"])) or "NONE"
            print(f"  {e['element_id']}  {e['name'][:46]:<46} -> {secs}")
        print()
        if errors(issues):
            rc = 1

    if a.verify_workbench:
        issues = verify_workbench(schemas, a.verify_workbench)
        _report_issues(issues, "WORKBENCH SCHEMA VERIFICATION")
        if errors(issues):
            rc = 1

    data = load_all_fixtures(schemas, a.fixtures)

    if a.render_template:
        text = render_template(cmap, schemas)
        with open(a.render_template, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {a.render_template} ({len(text)} bytes)")

    if a.render_sample:
        text = render_sample(cmap, schemas, data)
        with open(a.render_sample, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {a.render_sample} ({len(text)} bytes)")

    if a.render_map_csv:
        with open(a.render_map_csv, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(CONTENT_MAP_HEADERS)
            w.writerows(content_map_rows(cmap))
        print(f"wrote {a.render_map_csv}")

    if a.scope_guard:
        import scope_guard
        # Scan the RENDERED documents, not content_map.json. The guard reads
        # prose at the sentence level, and raw JSON splits a record's
        # scope-boundary context across lines - the exclusion's `name` ("Employee
        # or individual performance evaluation") lands on one line and the `why`
        # that disclaims it on another, so the neutralizing context is not in the
        # window. Rendered, that same record reads "Out of scope - Employee or
        # individual performance evaluation. This engagement ...", which is the
        # form a reader actually sees and the form the guard should judge. Every
        # string in the map reaches the template, so nothing goes unchecked.
        texts = [("template", render_template(cmap, schemas)),
                 ("sample", render_sample(cmap, schemas, data))]
        hits = []
        for name, t in texts:
            hits.extend(scope_guard.scan_text(t, source_id=name))
        print(scope_guard.render(hits, show_neutralized=True))
        if scope_guard.flagged(hits):
            rc = 1

    return rc


if __name__ == "__main__":
    raise SystemExit(main())
